/**
 * Translation architecture.
 *
 * Design decisions:
 *  - English is the complete reference dictionary; every key used in the UI is
 *    typed against it, so a missing key is a TypeScript error, not a blank label.
 *  - Urdu and Punjabi dictionaries are `Partial<Dictionary>`: any key not yet
 *    translated falls back to English rather than showing a raw key. This is the
 *    honest state of a first release and is visible in the language menu.
 *  - Keys are namespaced (`nav.*`, `home.*`, `assistant.*`) so that a page owns
 *    one block. This is ready for a library such as i18next but has no runtime
 *    dependency, which keeps the bundle small.
 */

